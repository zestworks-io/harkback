// @vitest-environment happy-dom
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { contextForRange, extractPage, firstSentence, inCodeBlock, ownHosts, proseText, rangeFor } from "../../src/lib/source/extract";

// happy-dom binds every Range to the window's document, so fixtures are loaded into it rather than a parsed copy.
const load = (name: string): Document => {
  const parsed = new DOMParser().parseFromString(readFileSync(`apps/extension/fixtures/${name}`, "utf8"), "text/html");
  document.documentElement.remove();
  document.appendChild(document.importNode(parsed.documentElement, true));
  return document;
};
const ARXIV = "https://arxiv.org/html/2106.09685";

const doc = load("arxiv-2106.09685.html");
const page = extractPage(doc, ARXIV);

describe("extractPage: arXiv", () => {
  it("reads the LaTeXML content, formulas as alttext, and nothing outside it", () => {
    expect(page.root.classList.contains("ltx_page_content")).toBe(true);
    expect(page.text).toContain("We apply LoRA to the attention weights");
    expect(page.text).toContain("W_0+BA");
    expect(page.text).not.toContain("navigation link");
    expect(page.text).not.toContain("Generated by LaTeXML");
  });

  it("tracks sections and the abstract's first sentence", () => {
    const intro = page.blocks.find((b) => page.text.slice(b.start, b.end).includes("We apply LoRA"))!;
    expect(intro.section).toBe("1 Introduction");
    expect(page.abstractFirstSentence).toBe(
      "We propose Low-Rank Adaptation, or LoRA, which freezes the pre-trained model weights and injects trainable rank decomposition matrices into each layer of the Transformer architecture.",
    );
  });

  it("maps text offsets back to DOM ranges, across inline elements", () => {
    const at = page.text.indexOf("LoRA to the attention");
    expect(rangeFor(page, at, at + 4)!.toString()).toBe("LoRA");
    const across = page.text.indexOf("Adapters add");
    expect(rangeFor(page, across, across + "Adapters add".length)!.toString()).toBe("Adapters add");
    expect(rangeFor(page, 5, 5)).toBeNull();
  });
});

describe("contextForRange", () => {
  const rangeOf = (setup: (r: Range) => void) => {
    const r = doc.createRange();
    setup(r);
    return r;
  };

  it("gives the paragraph, section and a quote selector for a word", () => {
    const ctx = contextForRange(
      page,
      rangeOf((r) => r.selectNodeContents(doc.getElementById("t-lora")!)),
    )!;
    expect(ctx.selection).toBe("LoRA");
    expect(ctx.paragraph).toBe("Fine-tuning large models is expensive. We apply LoRA to the attention weights of the Transformer.");
    expect(ctx.section).toBe("1 Introduction");
    expect(ctx.locator.exact).toBe("LoRA");
    expect(ctx.locator.prefix.endsWith("We apply")).toBe(true);
    expect(ctx.locator.suffix.startsWith("to the attention")).toBe(true);
    expect(ctx.locator.section).toBe("1 Introduction");
  });

  it("uses both paragraphs when the selection spans two", () => {
    const intro = doc.getElementById("p-intro")!.firstChild!;
    const math = doc.getElementById("p-math")!.firstChild!;
    const ctx = contextForRange(
      page,
      rangeOf((r) => {
        r.setStart(intro, 0);
        r.setEnd(math, 6);
      }),
    )!;
    expect(ctx.paragraph).toContain("Fine-tuning large models");
    expect(ctx.paragraph).toContain("The update is W_0+BA");
    const first = contextForRange(
      page,
      rangeOf((r) => r.selectNodeContents(doc.getElementById("t-lora")!)),
    )!;
    expect(ctx.paragraphId).toBe(first.paragraphId);
  });

  it("handles a selection inside a formula", () => {
    const ctx = contextForRange(
      page,
      rangeOf((r) => r.selectNodeContents(doc.getElementById("m-w")!)),
    )!;
    expect(ctx.selection).toBe("W");
    expect(ctx.paragraph).toContain("The update is W_0+BA where the rank is small.");
  });

  it("falls back to the nearest container for selections outside the content", () => {
    const nav = doc.querySelector("nav")!;
    const ctx = contextForRange(
      page,
      rangeOf((r) => r.selectNodeContents(nav)),
    )!;
    expect(ctx.paragraph).toBe("Introduction navigation link");
    expect(ctx.paragraphId.startsWith("outside:")).toBe(true);
  });

  it("keeps the selected term inside a paragraph longer than the limit", () => {
    const filler = "lorem ipsum dolor sit amet ".repeat(300);
    const long = document.createElement("div");
    long.innerHTML = `<p>${filler}the <b id="deep">kernel trick</b> maps data ${filler}</p>`;
    document.body.append(long);
    const p = extractPage(document, "https://example.com/", long);
    const r = document.createRange();
    r.selectNodeContents(document.getElementById("deep")!);
    const ctx = contextForRange(p, r)!;
    expect(ctx.paragraph.length).toBeLessThanOrEqual(2000);
    expect(ctx.paragraph).toContain("the kernel trick maps data");
    expect(ctx.locator.prefix.endsWith("the")).toBe(true);
    long.remove();
  });

  it("keeps the term in the fallback context of a long container outside the content", () => {
    const filler = "word ".repeat(1200);
    const box = document.createElement("div");
    box.innerHTML = `${filler}<i id="far">odd term</i> ${filler}`;
    document.body.append(box);
    const r = document.createRange();
    r.selectNodeContents(document.getElementById("far")!);
    const ctx = contextForRange(extractPage(document, "https://example.com/", document.createElement("div")), r)!;
    expect(ctx.paragraph).toContain("odd term");
    expect(ctx.locator.prefix.endsWith("word")).toBe(true);
    box.remove();
  });

  it("returns null for an empty selection", () => {
    expect(
      contextForRange(
        page,
        rangeOf((r) => r.setStart(doc.body, 0)),
      ),
    ).toBeNull();
  });
});

describe("extractPage: other sites", () => {
  it("skips navigation, asides, scripts, styles, hidden elements and the extension's own hosts", () => {
    const doc = load("blog.html");
    const host = doc.createElement("div");
    host.textContent = "OverlayOnlyTerm";
    doc.querySelector("article")!.append(host);
    ownHosts.add(host);
    const page = extractPage(doc, "https://blog.example.com/posts/adapters");
    expect(page.text).toContain("Adapters are small modules");
    expect(page.text).toContain("LoRA is a popular adapter");
    expect(page.text).toContain("Prefix tuning is another option");
    for (const term of [
      "NavOnlyTerm",
      "AsideOnlyTerm",
      "ScriptOnlyTerm",
      "StyleOnlyTerm",
      "HiddenOnlyTerm",
      "InlineHiddenTerm",
      "ClassHiddenTerm",
      "FooterOnlyTerm",
      "OverlayOnlyTerm",
    ]) {
      expect(page.text).not.toContain(term);
    }
    expect(page.abstractFirstSentence).toBe("A gentle introduction to adapters.");
  });
});

describe("firstSentence", () => {
  it("splits on Latin and CJK sentence ends", () => {
    expect(firstSentence("低秩适配。第二句。")).toBe("低秩适配。");
    expect(firstSentence("No end")).toBe("No end");
  });
});

describe("code blocks", () => {
  it("knows which text is in a code block, and leaves inline code with the prose", () => {
    const post = extractPage(load("devblog/post.html"), "https://example.github.io/posts/fine-tuning/");
    const inBlock = post.text.indexOf("CodeOnlyTerm");
    const inline = post.text.indexOf("LoRA adapters");
    expect(inBlock).toBeGreaterThan(0);
    expect(inCodeBlock(post, inBlock)).toBe(true);
    expect(inCodeBlock(post, inline)).toBe(false);
    expect(inCodeBlock(post, post.text.indexOf("We wanted"))).toBe(false);
    expect(inCodeBlock(post, -1)).toBe(false);

    const prose = proseText(post);
    expect(prose).not.toContain("CodeOnlyTerm");
    expect(prose).not.toContain("get_peft_model");
    expect(prose).toContain("The LoRA adapters add only");
    expect(prose).toContain("Here is the whole training configuration:\nThe LoRA adapters");
  });

  it("gives the whole text back for a page without code blocks", () => {
    expect(proseText(page)).toBe(page.text);
  });

  it("reads a pre of plain text as prose, and the lines of an embedded gist as code", () => {
    document.documentElement.innerHTML = `<body><main>
      <p>Intro paragraph about adapters.</p>
      <pre id="mail">From: someone
LoRA works well for us.</pre>
      <div class="gist"><table><tr><td class="blob-code blob-code-inner">config = GistOnlyTerm()</td></tr></table></div>
    </main></body>`;
    const mail = extractPage(document, "https://lists.example.org/pipermail/2026/001.html", document.querySelector("main")!);
    expect(inCodeBlock(mail, mail.text.indexOf("LoRA works"))).toBe(false);
    expect(inCodeBlock(mail, mail.text.indexOf("GistOnlyTerm"))).toBe(true);
    expect(proseText(mail)).toContain("LoRA works well");
    expect(proseText(mail)).not.toContain("GistOnlyTerm");
  });

  it("reads a highlighted pre without code, as Sphinx and GitHub READMEs write one, as code", () => {
    document.documentElement.innerHTML = `<body><main>
      <p>Some prose first.</p>
      <div class="highlight-python notranslate"><div class="highlight"><pre><span class="n">SphinxOnlyTerm</span> = 1</pre></div></div>
      <div class="highlight highlight-source-shell"><pre>ReadmeOnlyTerm --help</pre></div>
      <pre class="language-rust">PrismOnlyTerm</pre>
      <pre>Plain preformatted prose.</pre>
    </main></body>`;
    const docs = extractPage(document, "https://docs.example.org/", document.querySelector("main")!);
    const prose = proseText(docs);
    for (const term of ["SphinxOnlyTerm", "ReadmeOnlyTerm", "PrismOnlyTerm"]) expect(prose).not.toContain(term);
    expect(prose).toContain("Plain preformatted prose.");
  });

  it("does not count the page itself as code when its text sits inside a code sample", () => {
    document.documentElement.innerHTML = `<body><pre><code><span id="root">Everything here is the page.</span></code></pre></body>`;
    const inside = extractPage(document, "https://example.org/", document.getElementById("root")!);
    expect(inCodeBlock(inside, 0)).toBe(false);
    expect(proseText(inside)).toBe("Everything here is the page.");
  });
});
